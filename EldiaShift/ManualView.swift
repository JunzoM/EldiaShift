    var body: some View {
        let q = search.trimmingCharacters(in: .whitespaces)
        let shown: [Section_] = q.isEmpty ? Self.sections : Self.sections.compactMap { s in
            if s.title.localizedCaseInsensitiveContains(q) { return s }
            let items = s.items.filter { $0.0.localizedCaseInsensitiveContains(q) || $0.1.localizedCaseInsensitiveContains(q) }
            return items.isEmpty ? nil : Section_(icon: s.icon, title: s.title, items: items)
        }
        List {
            if shown.isEmpty {
                Text("「\(q)」に合う説明がありません").foregroundStyle(.secondary)
            }
            ForEach(shown) { s in
                Section {
                    ForEach(s.items, id: \.0) { item in
                        VStack(alignment: .leading, spacing: 4) {
                            Text(item.0).font(.subheadline.weight(.bold))
                            Text(item.1).font(.subheadline).foregroundStyle(.secondary)
                        }
                        .padding(.vertical, 2)
                    }
                } header: {
                    Label(s.title, systemImage: s.icon)
                }
            }
        }
        .searchable(text: $search, prompt: "マニュアルを検索")
        .navigationTitle("操作マニュアル")
        .navigationBarTitleDisplayMode(.inline)
    }
